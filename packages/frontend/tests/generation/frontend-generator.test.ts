import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { describe, expect, it } from 'vite-plus/test';

const root = process.cwd();

describe('frontend source generation', () => {
    it('keeps the override catalog synchronized with conventional defaults', async () => {
        const catalog = JSON.parse(await readFile(path.join(root, 'catalog.json'), 'utf8')) as {
            entries: Array<{ id: string; source: string }>;
        };
        const sources = await defaultSources();

        expect(catalog.entries.map((entry) => entry.source)).toEqual(sources);
    });

    it('generates the public UI registry from component and layout exports', async () => {
        const generated = await readFile(path.join(root, 'src/ui/generated.tsx'), 'utf8');

        expect(generated).toContain('This file is generated by scripts/generate-frontend.mjs.');
        expect(generated).toContain("component('components/ui/button', 'Button'");
        expect(generated).toContain("component('layouts/app-layout', 'AppLayout'");
        expect(generated).toContain("component('layouts/auth-layout', 'AuthLayout'");
        expect(generated).not.toContain('PanelLayout');
        expect(generated).toContain(
            "createOverridableFunction('components/ui/button', 'buttonVariants'",
        );
    });
});

async function defaultSources(): Promise<string[]> {
    const defaults = path.join(root, 'src/defaults');
    const entries = await readdir(defaults, { recursive: true, withFileTypes: true });

    return entries
        .filter((entry) => entry.isFile() && /\.tsx?$/.test(entry.name))
        .map((entry) => path.join(entry.parentPath, entry.name))
        .map((file) => path.relative(root, file).replaceAll(path.sep, '/'))
        .sort();
}
