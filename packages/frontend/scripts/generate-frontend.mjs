import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import ts from 'typescript';

const packageRoot = path.resolve(import.meta.dirname, '..');
const defaultsRoot = path.join(packageRoot, 'src/defaults');
const generatedUi = path.join(packageRoot, 'src/ui/generated.tsx');
const catalogFile = path.join(packageRoot, 'catalog.json');
const checkOnly = process.argv.includes('--check');

const files = await sourceFiles(defaultsRoot);
const entries = files.map((file) => ({ id: conventionId(file), source: relative(file) }));

validateEntries(entries);

const catalog = `${JSON.stringify({ entries }, null, 4)}\n`;
const ui = generateUi(files.filter((file) => /\/defaults\/(components|layouts)\//.test(posix(file))));

await synchronize(catalogFile, catalog);
await synchronize(generatedUi, ui);

async function sourceFiles(directory) {
    const children = await readdir(directory, { recursive: true, withFileTypes: true });

    return children
        .filter((entry) => entry.isFile() && /\.tsx?$/.test(entry.name))
        .map((entry) => path.join(entry.parentPath, entry.name))
        .sort((left, right) => relative(left).localeCompare(relative(right), 'en'));
}

function conventionId(file) {
    return posix(path.relative(defaultsRoot, file)).replace(/\.tsx?$/, '');
}

function relative(file) {
    return posix(path.relative(packageRoot, file));
}

function posix(value) {
    return value.split(path.sep).join('/');
}

function validateEntries(catalogEntries) {
    const ids = new Set();

    for (const entry of catalogEntries) {
        if (!/^components\/(?:ui\/[a-z0-9]+(?:-[a-z0-9]+)*|panel-[a-z0-9]+(?:-[a-z0-9]+)*)$/.test(entry.id)
            && !/^(hooks|layouts)\/[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.id)) {
            throw new Error(`Frontend default [${entry.source}] does not follow the lowercase kebab-case convention.`);
        }

        if (ids.has(entry.id)) {
            throw new Error(`Duplicate frontend default [${entry.id}].`);
        }

        ids.add(entry.id);
    }
}

function generateUi(uiFiles) {
    const configPath = path.join(packageRoot, 'tsconfig.json');
    const config = ts.readConfigFile(configPath, ts.sys.readFile);

    if (config.error) {
        throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
    }

    const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, packageRoot);
    const program = ts.createProgram(uiFiles, parsed.options);
    const checker = program.getTypeChecker();
    const modules = [];
    const runtimeNames = new Map();
    const typeNames = new Map();

    for (const [index, file] of uiFiles.entries()) {
        const source = program.getSourceFile(file);
        const moduleSymbol = source && checker.getSymbolAtLocation(source);

        if (!source || !moduleSymbol) {
            throw new Error(`Unable to inspect frontend default [${relative(file)}].`);
        }

        const values = [];
        const types = [];

        for (const exported of checker.getExportsOfModule(moduleSymbol)) {
            const symbol = exported.flags & ts.SymbolFlags.Alias
                ? checker.getAliasedSymbol(exported)
                : exported;
            const name = exported.getName();

            if (symbol.flags & ts.SymbolFlags.Value) {
                const declaration = symbol.valueDeclaration ?? symbol.declarations?.[0];
                const callable = declaration
                    ? checker.getTypeOfSymbolAtLocation(symbol, declaration).getCallSignatures().length > 0
                    : false;

                if (!callable) {
                    throw new Error(`Runtime export [${name}] from [${relative(file)}] must be callable.`);
                }

                claim(runtimeNames, name, file, 'runtime');
                values.push({ name, component: /^[A-Z][A-Za-z0-9]*$/.test(name) });
            } else if (symbol.flags & ts.SymbolFlags.Type) {
                claim(typeNames, name, file, 'type');
                types.push(name);
            }
        }

        if (values.length === 0) {
            throw new Error(`Frontend UI default [${relative(file)}] does not export a runtime value.`);
        }

        modules.push({
            file,
            id: conventionId(file),
            variable: `Default${index}`,
            specifier: `../defaults/${conventionId(file)}.js`,
            values: values.sort((left, right) => left.name.localeCompare(right.name, 'en')),
            types: types.sort((left, right) => left.localeCompare(right, 'en')),
        });
    }

    const lines = [
        '/* This file is generated by scripts/generate-frontend.mjs. Do not edit it manually. */',
        "import type { ComponentProps, ElementType } from 'react';",
        "import { createOverridableComponent, createOverridableFunction } from './runtime.js';",
        ...modules.map((module) => `import * as ${module.variable} from '${module.specifier}';`),
        '',
        'const component = <T extends ElementType>(id: string, name: string, fallback: T): T =>',
        '    createOverridableComponent(id, name, fallback);',
        '',
    ];

    for (const module of modules) {
        for (const value of module.values) {
            if (value.component) {
                lines.push(`export const ${value.name} = component('${module.id}', '${value.name}', ${module.variable}.${value.name});`);
            } else {
                lines.push(`export const ${value.name}: typeof ${module.variable}.${value.name} = createOverridableFunction('${module.id}', '${value.name}', ${module.variable}.${value.name});`);
            }
        }

        if (module.types.length > 0) {
            lines.push(`export type { ${module.types.join(', ')} } from '${module.specifier}';`);
        }

        for (const value of module.values.filter((item) => item.component)) {
            const props = `${value.name}Props`;

            if (!typeNames.has(props)) {
                claim(typeNames, props, module.file, 'generated type');
                lines.push(`export type ${props} = ComponentProps<typeof ${module.variable}.${value.name}>;`);
            }
        }

        lines.push('');
    }

    return `${lines.join('\n').trimEnd()}\n`;
}

function claim(names, name, file, kind) {
    const existing = names.get(name);

    if (existing) {
        throw new Error(`Duplicate ${kind} export [${name}] in [${relative(existing)}] and [${relative(file)}].`);
    }

    names.set(name, file);
}

async function synchronize(file, contents) {
    const current = await readFile(file, 'utf8').catch(() => undefined);

    if (current === contents) return;

    if (checkOnly) {
        throw new Error(`Generated frontend file [${relative(file)}] is out of date. Run [pnpm frontend:generate].`);
    }

    await writeFile(file, contents);
}
